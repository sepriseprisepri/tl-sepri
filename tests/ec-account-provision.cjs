/* Guardrails for EC account activation. No real credentials or network calls. */
"use strict";
const fs=require("node:fs");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const page=fs.readFileSync("index.html","utf8");
const ui=fs.readFileSync("ec-account-provision.js","utf8");
const edge=fs.readFileSync("supabase/functions/provision-ec-accounts/index.ts","utf8");
new vm.Script(ui);
assert.match(page,/"Aktivasi Akun EC"/);
assert.match(page,/ECAccountProvision\?\.render/);
assert.match(page,/src="\/ec-account-provision\.js"/);
assert.match(page,/currentProfile\?\.role==="ec"\?"provision-ec-accounts"/);
assert.match(page,/data\.role==="ec"\)\)/);
assert.match(ui,/functions\.invoke\("provision-ec-accounts"/);
assert.match(ui,/call\("preview"\)/);
assert.match(ui,/call\("activate"\)/);
assert.match(ui,/window\.confirm/);
assert.match(ui,/credentials\.forEach/);
assert.match(ui,/entries\.replaceChildren\(\)/);
assert.match(edge,/body\.action === "rotate_password"/);
assert.match(edge,/body\.action !== "activate"/);
assert.match(edge,/caller\.role !== "admin" \|\| caller\.is_active !== true/);
assert.match(edge,/activeManpower\.employee_id!==caller\.employee_id/);
assert.match(edge,/must_change_password: true/);
assert.match(edge,/is_active: false/);
assert.match(edge,/if \(createdNow\) \{/);
assert.match(edge,/existingProfile\.manpower_id!==person\.id/);
assert.match(edge,/admin\.auth\.admin\.createUser/);
assert.match(edge,/updateUserById\(callerId,\{password\}\)/);
assert.match(edge,/already_linked:manpower\.length-pending\.length/);
assert.match(edge,/to_create:pending\.length/);
assert.match(edge,/new Set\(manpower\.map/);
assert.doesNotMatch(edge,/expected 27 active ECs/);
assert.doesNotMatch(edge,/must_change_password:\s*false,\s*\n\s*\}\s*,\s*\{\s*onConflict/);
assert.doesNotMatch(edge,/console\.(log|error).*password/);
assert.match(edge,/return json\(req,\{ok:true,message:"Password baru tersimpan dan akun EC aktif"\}\)/);
assert.match(edge,/return json\(req,\{error:"Perubahan password EC tidak diperlukan/);
console.log("EC provisioning security checks passed: dynamic ECs, Admin gate, inactive new profiles, password rotation, legacy account preservation.");
