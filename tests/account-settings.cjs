"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const ui=fs.readFileSync("account-settings.js","utf8"),html=fs.readFileSync("index.html","utf8"),css=fs.readFileSync("futuristic-ui.css","utf8");
new vm.Script(ui);
const scripts=[...html.matchAll(/<script(?: [^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(Boolean);
for(const code of scripts)new vm.Script(code);
const sandbox={window:{},Intl,Date,Number,String,Error,Map,URLSearchParams,console};
vm.runInNewContext(ui,sandbox);
const {passwordValid}=sandbox.window.SamsungSettings;
assert.equal(passwordValid("Password2026Secure"),true);
assert.equal(passwordValid("short123"),false);
assert.equal(passwordValid("passwordwithoutnumbers"),false);
assert.equal(passwordValid("1234567890123456"),false);
assert.equal(passwordValid("Password0123456789".repeat(10)),false);
assert.match(html,/src="\/account-settings\.js"/);
assert.match(html,/window\.SamsungSettings\.render/);
assert.match(html,/window\.SamsungSettings\.restoreTheme\(data\.id\)/);
assert.match(html,/window\.SamsungSettings\?\.reset\(\)/);
assert.equal((html.match(/\["Pengaturan","⚙"\]/g)||[]).length,4);
assert.match(ui,/roleNames=\{admin:"Administrator",tl:"Team Leader",tso:"TSO",ec:"Experience Consultant"\}/);
assert.match(ui,/currentPassword===newPassword/);
assert.match(ui,/newPassword!==confirmation/);
assert.match(ui,/POST"\s*,?headers,signal:controller\.signal/);
assert.match(ui,/\/auth\/v1\/token\?grant_type=password/);
assert.match(ui,/\/auth\/v1\/user/);
assert.match(ui,/method:"PUT"/);
assert.match(ui,/session\.user\?\.id!==ctx\.profile\.id/);
assert.match(ui,/Authorization:"Bearer "\+session\.access_token/);
assert.doesNotMatch(ui,/localStorage\.setItem\([^,]+,\s*(?:currentPassword|newPassword|password)/);
assert.doesNotMatch(ui,/service_role|sb_secret_/);
assert.match(ui,/user_ui_preferences\?on_conflict=user_id/);
assert.match(ui,/table_density:density/);
assert.match(ui,/profile\.role==="ec"/);
assert.match(ui,/store_assignments/);
assert.match(ui,/async function render\(ctx,mount\)/);
assert.match(css,/#app-view \.settings-input/);
assert.match(css,/body\.settings-light #app-view/);
assert.match(css,/@media\(max-width:640px\)/);
console.log("Settings regression passed: all roles, secure current-password verification, preferences, mobile styles and no secret storage.");
