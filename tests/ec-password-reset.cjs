/* EC individual password reset invariants, no live Auth operations. */
"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const edge=fs.readFileSync("supabase/functions/provision-ec-accounts/index.ts","utf8");
const ui=fs.readFileSync("ec-password-reset.js","utf8");
const index=fs.readFileSync("index.html","utf8");
new vm.Script(ui);
assert.match(index,/src="\/ec-password-reset\.js"/);
assert.match(index,/window\.ECPasswordReset\?\.render/);
assert.match(ui,/ctx\.profile\?\.role!=="admin"/);
assert.match(ui,/action:"list_ec_accounts"/);
assert.match(ui,/action:"reset_password",employee_id:person\.employee_id/);
assert.match(ui,/typed\.value\.trim\(\)!==person\.employee_id/);
assert.match(ui,/window\.confirm/);
assert.match(ui,/secret\.textContent=""/);
assert.match(ui,/temporaryPassword=null/);
assert.match(edge,/body\.action==="list_ec_accounts" \|\| body\.action==="reset_password"/);
assert.match(edge,/caller\.role!=="admin" \|\| caller\.is_active!==true/);
assert.match(edge,/person\.employee_id===employeeId/);
assert.match(edge,/targetProfile\.role!=="ec"/);
assert.match(edge,/targetProfile\.employee_id!==person\.employee_id/);
assert.match(edge,/admin\.auth\.admin\.getUserById\(targetProfile\.id\)/);
assert.match(edge,/authUser\.user\.email\?\.toLowerCase\(\)!==expectedEmail/);
assert.match(edge,/is_active:false,must_change_password:true/);
assert.match(edge,/updateUserById\(targetProfile\.id,\{password:temporaryPassword\}\)/);
assert.match(edge,/temporary_password:temporaryPassword/);
assert.match(edge,/if\(body\.action==="preview"\)/);
assert.match(edge,/body\.action === "rotate_password"/);
assert.doesNotMatch(edge,/console\.(log|error|info)\(.*temporaryPassword/);
assert.doesNotMatch(edge,/updateUserById\([^\n]+\{password:"Samsung123456"/);
console.log("EC reset checks passed: Admin authorization, identity linkage, individual target, forced rotation, one-time credentials.");
