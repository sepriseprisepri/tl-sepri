/* Safe static regression test. Does NOT call Supabase, reset a user, or expose a secret. */
const fs=require("node:fs");
const assert=require("node:assert/strict");
const vm=require("node:vm");
const html=fs.readFileSync("index.html","utf8");
const ui=fs.readFileSync("password-recovery.js","utf8");
const backend=fs.readFileSync("supabase/functions/password-recovery/index.ts","utf8");
const migration=fs.readFileSync("docs/sql/20261110-password-recovery-approval-draft.sql","utf8");
const guard=fs.readFileSync("docs/sql/20261110-password-recovery-rls-guard-staging.sql","utf8");
const ecBackend=fs.readFileSync("supabase/functions/provision-ec-accounts/index.ts","utf8");
const tlBackend=fs.readFileSync("supabase/functions/provision-tl-bmu/index.ts","utf8");
new vm.Script(ui,{filename:"password-recovery.js"});
assert.match(html,/<script src="\/password-recovery\.js"><\/script>/);
assert.match(html,/SamsungPasswordRecovery\?\.open\(\)/);
assert.match(html,/SamsungPasswordRecovery\?\.renderAdmin/);
assert.match(ui,/Lupa Password\?/);
assert.match(ui,/data-recovery-request="forgot"/);
assert.match(ui,/data-recovery-request="reset"/);
assert.match(ui,/role","dialog"/);
assert.match(ui,/aria-modal","true"/);
assert.match(ui,/data-recovery-action="approve"/);
assert.match(ui,/data-recovery-action="reissue"/);
assert.match(ui,/data-one-time-secret/);
assert.match(ui,/data-mark-delivered/);
assert.match(backend,/auth\.getUser\(token\)/);
assert.match(backend,/caller\.role!=="admin"/);
assert.match(backend,/caller\.must_change_password!==true/);
assert.match(backend,/24\*3600_000/);
assert.match(backend,/randomPassword\(\)/);
assert.doesNotMatch(migration,/\btemporary_password\s+(?:text|varchar)/i,"Never store a plaintext password");
assert.match(migration,/ENABLE ROW LEVEL SECURITY/);
assert.match(migration,/REVOKE ALL ON TABLE/);
assert.ok(html.includes('data?.error==="NO_RECOVERY_REQUEST"'));
assert.ok(!html.includes('response.status===404||data?.error'));
assert.ok(ui.includes("window.SAMSUNG_TURNSTILE_SITE_KEY"));
assert.ok(ui.includes("captcha_token:captchaToken"));
assert.ok(backend.includes("verifyHuman(body.captcha_token,captchaSecret,"));
assert.ok(backend.includes("https://challenges.cloudflare.com/turnstile/v0/siteverify"));
assert.ok(backend.includes('admin.rpc("password_recovery_claim_rate"'));
assert.ok(!backend.includes("ipCount"));
assert.ok(migration.includes("ON CONFLICT (requester_fingerprint,bucket_started_at)"));
assert.ok(migration.includes("WHERE b.attempts<5"));
assert.ok(migration.includes("GRANT EXECUTE ON FUNCTION public.password_recovery_claim_rate(text) TO service_role"));
assert.ok(guard.includes("p.must_change_password IS FALSE"));
assert.ok(ecBackend.includes('.from("password_recovery_requests")'));
assert.ok(ecBackend.includes('item.status!=="completed"'));
assert.ok(tlBackend.includes('item.status!=="completed"'));
assert.ok(tlBackend.includes('caller.must_change_password'));
console.log("Password recovery static UI + security gates passed; DB integration runs in separate workflow.");
